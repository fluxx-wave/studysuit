using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using System.Windows.Controls;
using System.Windows.Documents;
using Microsoft.Web.WebView2.Core;

namespace StudySuit.PdfReader.Services;

/// <summary>
/// Centralized manager for WebView2 lifetime, environment options, and aggressive memory recycling.
/// Prevents Chromium process bloat and memory accumulation across News and 3D viewers.
/// </summary>
public static class WebViewMemoryManager
{
    private static CoreWebView2Environment? _sharedEnvironment;
    private static readonly SemaphoreSlim _envLock = new(1, 1);

    /// <summary>
    /// Returns a single shared CoreWebView2Environment with strict process count limits and back-forward cache disabled.
    /// </summary>
    public static async Task<CoreWebView2Environment> GetSharedEnvironmentAsync()
    {
        if (_sharedEnvironment != null)
        {
            return _sharedEnvironment;
        }

        await _envLock.WaitAsync().ConfigureAwait(false);
        try
        {
            if (_sharedEnvironment != null)
            {
                return _sharedEnvironment;
            }

            string userDataFolder = Path.Combine(
                Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
                "StudySuit",
                "WebView2Data");

            Directory.CreateDirectory(userDataFolder);

            // Strict command line arguments to throttle Chromium process count and memory consumption:
            // 1. --renderer-process-limit=1 limits Chromium to a single renderer process across the entire application
            // 2. --disable-features=BackForwardCache prevents caching traversed pages in RAM
            // 3. --disable-gpu-shader-disk-cache and --disable-background-networking cut background caching & tasks
            // 4. --js-flags=--max-old-space-size=128 enforces aggressive V8 garbage collection to keep heap under 128MB
            string browserArgs = "--renderer-process-limit=1 --disable-features=BackForwardCache,MediaEngagementBypassAutoplayPolicies --disable-gpu-shader-disk-cache --disable-background-networking --js-flags=--max-old-space-size=128";

            var options = new CoreWebView2EnvironmentOptions(browserArgs);

            _sharedEnvironment = await CoreWebView2Environment.CreateAsync(null, userDataFolder, options).ConfigureAwait(false);
            return _sharedEnvironment;
        }
        catch (Exception ex)
        {
            System.Diagnostics.Debug.WriteLine($"[WebViewMemoryManager] Custom env init failed, falling back: {ex.Message}");
            _sharedEnvironment = await CoreWebView2Environment.CreateAsync().ConfigureAwait(false);
            return _sharedEnvironment;
        }
        finally
        {
            _envLock.Release();
        }
    }

    /// <summary>
    /// Configures CoreWebView2 instance with aggressive memory reclamation target.
    /// </summary>
    public static void ApplyLowMemoryTarget(CoreWebView2? core)
    {
        if (core == null) return;
        try
        {
            core.MemoryUsageTargetLevel = CoreWebView2MemoryUsageTargetLevel.Low;
        }
        catch { }
    }

    /// <summary>
    /// Immediately releases memory of a webview by navigating to about:blank and purging cache.
    /// </summary>
    public static async Task ClearPageMemoryAsync(Microsoft.Web.WebView2.Wpf.WebView2? webView)
    {
        if (webView == null) return;
        try
        {
            if (webView.CoreWebView2 != null)
            {
                webView.CoreWebView2.Navigate("about:blank");
                webView.CoreWebView2.MemoryUsageTargetLevel = CoreWebView2MemoryUsageTargetLevel.Low;

                await webView.CoreWebView2.Profile.ClearBrowsingDataAsync(
                    CoreWebView2BrowsingDataKinds.DiskCache |
                    CoreWebView2BrowsingDataKinds.CacheStorage |
                    CoreWebView2BrowsingDataKinds.ServiceWorkers).ConfigureAwait(false);
            }
        }
        catch { }
    }
}

/// <summary>
/// Active 3D model pool that caches and re-parents initialized 3D WebView blocks during response streaming.
/// Prevents creating a new WebView2 on every token generated by the AI assistant.
/// </summary>
public static class Active3DViewPool
{
    private sealed record Pooled3DView(
        string EmbedUrl,
        Border OuterBorder,
        Border WebViewBorder,
        Microsoft.Web.WebView2.Wpf.WebView2 WebView,
        DateTime LastAccessedUtc);

    private static readonly Dictionary<string, Pooled3DView> _pool = new(StringComparer.OrdinalIgnoreCase);
    private const int MaxActive3DViews = 2; // Strict limit: at most 2 active 3D models in memory across app

    public static bool TryGetExistingBlock(
        string embedUrl,
        out Border? outerBlock,
        out Border? webViewBorder,
        out Microsoft.Web.WebView2.Wpf.WebView2? webView)
    {
        lock (_pool)
        {
            if (_pool.TryGetValue(embedUrl, out var entry))
            {
                _pool[embedUrl] = entry with { LastAccessedUtc = DateTime.UtcNow };

                // Detach from previous parent container so it can be re-parented cleanly in new FlowDocument
                if (entry.OuterBorder.Parent is BlockUIContainer oldBlockContainer)
                {
                    oldBlockContainer.Child = null;
                }
                else if (entry.OuterBorder.Parent is Panel oldPanel)
                {
                    oldPanel.Children.Remove(entry.OuterBorder);
                }

                outerBlock = entry.OuterBorder;
                webViewBorder = entry.WebViewBorder;
                webView = entry.WebView;
                return true;
            }

            outerBlock = null;
            webViewBorder = null;
            webView = null;
            return false;
        }
    }

    public static void Register(
        string embedUrl,
        Border outerBlock,
        Border webViewBorder,
        Microsoft.Web.WebView2.Wpf.WebView2 webView)
    {
        lock (_pool)
        {
            // Evict and dispose the oldest view if exceeding max limit
            while (_pool.Count >= MaxActive3DViews)
            {
                var oldest = _pool.OrderBy(kv => kv.Value.LastAccessedUtc).First();
                _pool.Remove(oldest.Key);
                DisposePooledView(oldest.Value);
            }

            _pool[embedUrl] = new Pooled3DView(embedUrl, outerBlock, webViewBorder, webView, DateTime.UtcNow);
        }
    }

    private static void DisposePooledView(Pooled3DView item)
    {
        try
        {
            item.WebView.Dispatcher.Invoke(() =>
            {
                try
                {
                    if (item.WebViewBorder.Child == item.WebView)
                    {
                        item.WebViewBorder.Child = null;
                    }

                    // Explicitly calling Dispose terminates all underlying Chromium processes
                    item.WebView.Dispose();
                }
                catch { }
            });
        }
        catch { }
    }

    public static void ClearAndDisposeAll()
    {
        lock (_pool)
        {
            foreach (var item in _pool.Values)
            {
                DisposePooledView(item);
            }
            _pool.Clear();
        }
    }
}
